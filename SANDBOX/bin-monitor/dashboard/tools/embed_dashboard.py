#!/usr/bin/env python3
"""Embed the existing offline dashboard in ESP32 flash; no external web assets."""
from pathlib import Path
import argparse
import hashlib
import sys

ROOT = Path(__file__).resolve().parents[1]
ASSETS = [
    ('/', 'index.html', 'text/html; charset=utf-8'),
    ('/index.html', 'index.html', 'text/html; charset=utf-8'),
    ('/app.js', 'app.js', 'text/javascript; charset=utf-8'),
    ('/model.js', 'model.js', 'text/javascript; charset=utf-8'),
    ('/bin-view.js', 'bin-view.js', 'text/javascript; charset=utf-8'),
    ('/bin-view.css', 'bin-view.css', 'text/css; charset=utf-8'),
    ('/monitor.css', 'monitor.css', 'text/css; charset=utf-8'),
    ('/vendor/theme.css', 'vendor/theme.css', 'text/css; charset=utf-8'),
    ('/vendor/js/dom.js', 'vendor/js/dom.js', 'text/javascript; charset=utf-8'),
    ('/vendor/js/widgets/window.js', 'vendor/js/widgets/window.js', 'text/javascript; charset=utf-8'),
    ('/assets/icons.svg', 'assets/icons.svg', 'image/svg+xml'),
    ('/assets/school-logo.png', 'assets/school-logo.png', 'image/png'),
    ('/assets/esp32-wiring.svg', 'assets/esp32-wiring.svg', 'image/svg+xml'),
    ('/README.md', 'README.md', 'text/plain; charset=utf-8'),
]

def generate():
    lines = ['// Generated by tools/embed_dashboard.py. Re-run after dashboard edits.',
             '#pragma once', '#include <Arduino.h>',
             'struct DashboardAsset { const char* path; const char* contentType; const uint8_t* data; size_t size; };']
    ids = {}
    total = 0
    for _, filename, _ in ASSETS:
        if filename in ids:
            continue
        name = f'dashboard_asset_{len(ids)}'
        ids[filename] = name
        data = (ROOT / filename).read_bytes()
        total += len(data)
        lines.append(f'// {filename}: {len(data)} bytes, SHA256 {hashlib.sha256(data).hexdigest()}')
        lines.append(f'static const uint8_t {name}[] PROGMEM = {{')
        for start in range(0, len(data), 20):
            lines.append('  ' + ','.join(f'0x{byte:02x}' for byte in data[start:start + 20]) + ',')
        lines.append('};')
    lines.append('static const DashboardAsset DASHBOARD_ASSETS[] = {')
    for path, filename, mime in ASSETS:
        name = ids[filename]
        lines.append(f'  {{"{path}", "{mime}", {name}, sizeof({name})}},')
    lines.extend(['};', 'static const size_t DASHBOARD_ASSET_COUNT = sizeof(DASHBOARD_ASSETS) / sizeof(DASHBOARD_ASSETS[0]);', ''])
    return '\n'.join(lines), total

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if firmware assets are out of date')
    args = parser.parse_args()
    content, total = generate()
    target = ROOT / 'firmware/bin_monitor/dashboard_assets.h'
    if args.check:
        if not target.exists() or target.read_text() != content:
            sys.exit('Firmware dashboard assets are stale. Run python3 tools/embed_dashboard.py')
        print(f'PASS: embedded dashboard matches {len(ASSETS)} routes ({total:,} flash bytes).')
    else:
        target.write_text(content)
        print(f'Generated {target.relative_to(ROOT)}: {len(ASSETS)} routes, {total:,} flash bytes.')
